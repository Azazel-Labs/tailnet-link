//! The local proxy on 127.0.0.1: sends each request to the tailnet that owns
//! its name. Also serves the PAC file (the rules the system proxy setting
//! points at), and lets a second copy of the app ask this one to show itself.

use std::fmt::Write as _;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, PoisonError, RwLock};
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::net::{TcpListener, TcpStream};

use crate::socks;
use crate::tsnet::SocksTarget;

/// Picks the tailnet for a host name.
pub trait Router: Send + Sync + 'static {
    fn route(&self, host: &str) -> Option<SocksTarget>;
    /// A second copy of the app asked us to show our window.
    fn show(&self);
}

/// The PAC rules and whether routing is on (off = PAC says "everything direct").
pub struct PacState {
    pac: RwLock<Vec<u8>>,
    active: AtomicBool,
}

pub const DIRECT_PAC: &str = "// Tailnet Link: routing is off, everything goes direct.\nfunction FindProxyForURL(url, host) { return \"DIRECT\"; }\n";

impl PacState {
    pub fn new() -> Self {
        PacState { pac: RwLock::new(DIRECT_PAC.as_bytes().to_vec()), active: AtomicBool::new(false) }
    }
    pub fn set_pac(&self, pac: Vec<u8>) {
        *self.pac.write().unwrap_or_else(PoisonError::into_inner) = pac;
    }
    pub fn set_active(&self, on: bool) {
        self.active.store(on, Ordering::SeqCst);
    }
    pub fn current(&self) -> Vec<u8> {
        if self.active.load(Ordering::SeqCst) {
            self.pac.read().unwrap_or_else(PoisonError::into_inner).clone()
        } else {
            DIRECT_PAC.as_bytes().to_vec()
        }
    }
}

/// PAC script sending the given domains to `proxy_addr`, everything else direct.
pub fn build_pac(proxy_addr: &str, domains: &[String]) -> Vec<u8> {
    let mut s = String::from(
        "// Generated by Tailnet Link. Only these domains go through the other tailnets.\n\
         function FindProxyForURL(url, host) {\n  host = host.toLowerCase();\n",
    );
    for d in domains {
        let d = d.trim().trim_matches('.').to_lowercase();
        if d.is_empty() {
            continue;
        }
        // JSON string literals are valid JavaScript string literals.
        let q = serde_json::Value::from(d.as_str());
        let dq = serde_json::Value::from(format!(".{d}"));
        let _ = writeln!(s, "  if (host === {q} || dnsDomainIs(host, {dq})) return \"PROXY {proxy_addr}\";");
    }
    s.push_str("  return \"DIRECT\";\n}\n");
    s.into_bytes()
}

/// Same PAC address apart from the ?v= version.
pub fn is_our_pac(a: &str, b: &str) -> bool {
    let base = |u: &str| u.split('?').next().unwrap_or("").to_owned();
    !a.is_empty() && base(a) == base(b)
}

pub async fn serve(listener: TcpListener, router: Arc<dyn Router>, pac: Arc<PacState>) {
    loop {
        let Ok((conn, _)) = listener.accept().await else {
            continue;
        };
        let (router, pac) = (router.clone(), pac.clone());
        tokio::spawn(async move {
            if let Err(e) = handle(conn, router, pac).await {
                log::debug!("proxy connection: {e}");
            }
        });
    }
}

const MAX_HEAD: usize = 64 * 1024;

async fn handle(mut client: TcpStream, router: Arc<dyn Router>, pac: Arc<PacState>) -> std::io::Result<()> {
    // Read the request head.
    let mut buf = Vec::with_capacity(4096);
    let head_len = loop {
        let mut chunk = [0u8; 4096];
        let n = client.read(&mut chunk).await?;
        if n == 0 {
            return Ok(());
        }
        buf.extend_from_slice(&chunk[..n]);
        if let Some(i) = find(&buf, b"\r\n\r\n") {
            break i + 4;
        }
        if buf.len() > MAX_HEAD {
            return respond(&mut client, 431, "text/plain", b"request head too large").await;
        }
    };

    let mut headers = [httparse::EMPTY_HEADER; 96];
    let mut req = httparse::Request::new(&mut headers);
    if req.parse(&buf[..head_len]).is_err() {
        return respond(&mut client, 400, "text/plain", b"bad request").await;
    }
    let method = req.method.unwrap_or("").to_owned();
    let path = req.path.unwrap_or("").to_owned();
    let rest = buf[head_len..].to_vec();

    if method.eq_ignore_ascii_case("CONNECT") {
        let (host, port) = split_host_port(&path, 443);
        let Some(target) = router.route(&host) else {
            return respond(&mut client, 502, "text/plain", format!("no connected tailnet handles {host}").as_bytes())
                .await;
        };
        let mut up = match socks::connect(&target, &host, port).await {
            Ok(s) => s,
            Err(e) => {
                log::info!("connect {host}:{port}: {e}");
                return respond(&mut client, 502, "text/plain", format!("Tailnet Link: {e}").as_bytes()).await;
            }
        };
        client.write_all(b"HTTP/1.1 200 Connection Established\r\n\r\n").await?;
        if !rest.is_empty() {
            up.write_all(&rest).await?;
        }
        let _ = tokio::io::copy_bidirectional(&mut client, &mut up).await;
        return Ok(());
    }

    if let Some(after) = path.strip_prefix("http://") {
        // Plain-HTTP proxy request: http://host[:port]/path
        let (authority, origin) = match after.find('/') {
            Some(i) => (&after[..i], &after[i..]),
            None => (after, "/"),
        };
        let (host, port) = split_host_port(authority, 80);
        let Some(target) = router.route(&host) else {
            return respond(&mut client, 502, "text/plain", format!("no connected tailnet handles {host}").as_bytes())
                .await;
        };
        let mut up = match socks::connect(&target, &host, port).await {
            Ok(s) => s,
            Err(e) => return respond(&mut client, 502, "text/plain", format!("Tailnet Link: {e}").as_bytes()).await,
        };
        // Rewrite to an origin-form request; one request per connection.
        let mut out = format!("{method} {origin} HTTP/1.1\r\n");
        for h in req.headers.iter() {
            let name = h.name.to_ascii_lowercase();
            if matches!(name.as_str(), "proxy-connection" | "proxy-authorization" | "connection" | "keep-alive") {
                continue;
            }
            out.push_str(h.name);
            out.push_str(": ");
            out.push_str(&String::from_utf8_lossy(h.value));
            out.push_str("\r\n");
        }
        out.push_str("Connection: close\r\n\r\n");
        up.write_all(out.as_bytes()).await?;
        if !rest.is_empty() {
            up.write_all(&rest).await?;
        }
        let _ = tokio::io::copy_bidirectional(&mut client, &mut up).await;
        return Ok(());
    }

    // Requests addressed to the proxy itself.
    let local_path = path.split('?').next().unwrap_or("");
    match (method.as_str(), local_path) {
        ("GET", "/proxy.pac" | "/wpad.dat") => {
            respond(&mut client, 200, "application/x-ns-proxy-autoconfig", &pac.current()).await
        }
        ("POST", "/show") => {
            // A custom header: browsers can't send it cross-site without
            // permission, so web pages can't trigger this.
            let ok = req.headers.iter().any(|h| h.name.eq_ignore_ascii_case("x-tailnet-link") && h.value == b"show");
            if ok {
                router.show();
                respond(&mut client, 204, "text/plain", b"").await
            } else {
                respond(&mut client, 403, "text/plain", b"forbidden").await
            }
        }
        _ => respond(&mut client, 200, "text/plain; charset=utf-8", b"Tailnet Link is running.\n").await,
    }
}

async fn respond(c: &mut TcpStream, code: u16, ctype: &str, body: &[u8]) -> std::io::Result<()> {
    let reason = match code {
        200 => "OK",
        204 => "No Content",
        400 => "Bad Request",
        403 => "Forbidden",
        431 => "Request Header Fields Too Large",
        _ => "Bad Gateway",
    };
    let head = format!(
        "HTTP/1.1 {code} {reason}\r\nContent-Type: {ctype}\r\nContent-Length: {}\r\nCache-Control: no-cache, no-store\r\nConnection: close\r\n\r\n",
        body.len()
    );
    c.write_all(head.as_bytes()).await?;
    c.write_all(body).await?;
    c.shutdown().await
}

fn find(h: &[u8], needle: &[u8]) -> Option<usize> {
    h.windows(needle.len()).position(|w| w == needle)
}

/// "host:port" / "[v6]:port" / "host" -> (host, port)
pub fn split_host_port(s: &str, default_port: u16) -> (String, u16) {
    if let Some(rest) = s.strip_prefix('[')
        && let Some((h, p)) = rest.split_once(']')
    {
        let port = p.strip_prefix(':').and_then(|p| p.parse().ok()).unwrap_or(default_port);
        return (h.to_owned(), port);
    }
    match s.rsplit_once(':') {
        Some((h, p)) if !h.contains(':') => (h.to_owned(), p.parse().unwrap_or(default_port)),
        _ => (s.to_owned(), default_port),
    }
}

/// Serves one port forward until the task is aborted.
pub async fn serve_forward(listener: TcpListener, target: String, router: Arc<dyn Router>) {
    let (host, port) = split_host_port(&target, 0);
    loop {
        let Ok((mut conn, _)) = listener.accept().await else {
            continue;
        };
        let (router, host) = (router.clone(), host.clone());
        tokio::spawn(async move {
            let Some(t) = router.route(&host) else {
                log::info!("forward to {host}: no connected tailnet handles it");
                return;
            };
            match socks::connect(&t, &host, port).await {
                Ok(mut up) => {
                    let _ = tokio::io::copy_bidirectional(&mut conn, &mut up).await;
                }
                Err(e) => log::info!("forward to {host}:{port}: {e}"),
            }
        });
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pac_rules() {
        let pac = String::from_utf8(build_pac("127.0.0.1:1055", &["example.ts.net".into()])).unwrap();
        assert!(pac.contains(r#"dnsDomainIs(host, ".example.ts.net")"#));
        assert!(pac.contains(r#"host === "example.ts.net""#));
        assert!(pac.contains(r#"return "PROXY 127.0.0.1:1055""#));
        assert!(pac.contains(r#"return "DIRECT""#));
    }

    #[test]
    fn pac_state_goes_direct_when_inactive() {
        let s = PacState::new();
        s.set_pac(build_pac("127.0.0.1:1055", &["a.ts.net".into()]));
        assert!(String::from_utf8(s.current()).unwrap().contains("DIRECT\"; }"));
        s.set_active(true);
        assert!(String::from_utf8(s.current()).unwrap().contains("PROXY"));
    }

    #[test]
    fn our_pac_matching() {
        assert!(is_our_pac("http://127.0.0.1:1055/proxy.pac?v=1", "http://127.0.0.1:1055/proxy.pac?v=2"));
        assert!(!is_our_pac("http://corp/x.pac", "http://127.0.0.1:1055/proxy.pac?v=1"));
        assert!(!is_our_pac("", "http://127.0.0.1:1055/proxy.pac?v=1"));
    }

    #[test]
    fn host_ports() {
        assert_eq!(split_host_port("a.ts.net:443", 80), ("a.ts.net".into(), 443));
        assert_eq!(split_host_port("a.ts.net", 80), ("a.ts.net".into(), 80));
        assert_eq!(split_host_port("[fd7a::1]:22", 80), ("fd7a::1".into(), 22));
    }

    // End to end: a CONNECT through the proxy, via a fake SOCKS "tailnet".
    struct FakeRouter(String);
    impl Router for FakeRouter {
        fn route(&self, host: &str) -> Option<SocksTarget> {
            host.ends_with(".ts.net").then(|| SocksTarget { addr: self.0.clone(), user: "u".into(), pass: "p".into() })
        }
        fn show(&self) {}
    }

    async fn fake_socks_echo() -> String {
        let ln = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let addr = ln.local_addr().unwrap().to_string();
        tokio::spawn(async move {
            loop {
                let (mut conn, _) = ln.accept().await.unwrap();
                tokio::spawn(async move {
                    let mut greeting = [0u8; 3];
                    conn.read_exact(&mut greeting).await.unwrap();
                    conn.write_all(&[5, 2]).await.unwrap();
                    let mut auth = [0u8; 2];
                    conn.read_exact(&mut auth).await.unwrap();
                    let mut skip = vec![0u8; auth[1] as usize];
                    conn.read_exact(&mut skip).await.unwrap();
                    let mut pl = [0u8; 1];
                    conn.read_exact(&mut pl).await.unwrap();
                    let mut skip = vec![0u8; pl[0] as usize];
                    conn.read_exact(&mut skip).await.unwrap();
                    conn.write_all(&[1, 0]).await.unwrap();
                    let mut req = [0u8; 5];
                    conn.read_exact(&mut req).await.unwrap();
                    let mut skip = vec![0u8; req[4] as usize + 2];
                    conn.read_exact(&mut skip).await.unwrap();
                    conn.write_all(&[5, 0, 0, 1, 0, 0, 0, 0, 0, 0]).await.unwrap();
                    // echo
                    let (mut r, mut w) = conn.split();
                    let _ = tokio::io::copy(&mut r, &mut w).await;
                });
            }
        });
        addr
    }

    #[tokio::test]
    async fn connect_through_proxy() {
        let socks_addr = fake_socks_echo().await;
        let ln = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let paddr = ln.local_addr().unwrap();
        tokio::spawn(serve(ln, Arc::new(FakeRouter(socks_addr)), Arc::new(PacState::new())));

        let mut c = TcpStream::connect(paddr).await.unwrap();
        c.write_all(b"CONNECT wiki.example.ts.net:443 HTTP/1.1\r\nHost: x\r\n\r\nping").await.unwrap();
        let mut resp = vec![0u8; 39];
        c.read_exact(&mut resp).await.unwrap();
        assert!(resp.starts_with(b"HTTP/1.1 200"));
        let mut echo = [0u8; 4];
        c.read_exact(&mut echo).await.unwrap();
        assert_eq!(&echo, b"ping");

        // Unknown domain: 502.
        let mut c = TcpStream::connect(paddr).await.unwrap();
        c.write_all(b"CONNECT example.com:443 HTTP/1.1\r\n\r\n").await.unwrap();
        let mut resp = String::new();
        c.read_to_string(&mut resp).await.unwrap();
        assert!(resp.starts_with("HTTP/1.1 502"), "{resp}");

        // PAC served.
        let mut c = TcpStream::connect(paddr).await.unwrap();
        c.write_all(b"GET /proxy.pac HTTP/1.1\r\nHost: x\r\n\r\n").await.unwrap();
        let mut resp = String::new();
        c.read_to_string(&mut resp).await.unwrap();
        assert!(resp.contains("application/x-ns-proxy-autoconfig") && resp.contains("FindProxyForURL"));

        // /show needs POST + header.
        let mut c = TcpStream::connect(paddr).await.unwrap();
        c.write_all(b"POST /show HTTP/1.1\r\nHost: x\r\n\r\n").await.unwrap();
        let mut resp = String::new();
        c.read_to_string(&mut resp).await.unwrap();
        assert!(resp.starts_with("HTTP/1.1 403"));
    }
}
