//! The local proxy on 127.0.0.1: sends each request to the tailnet that owns
//! its name. Also serves the PAC file (the rules the system proxy setting
//! points at), lets a second copy of the app ask this one to show itself, and
//! answers `tl` (see src/bin/tl.rs).
//!
//! It runs twice. The system proxy setting's copy refuses names no tailnet
//! carries. The terminal copy, which `tl` points proxy-aware tools at,
//! connects to those directly instead, so `tl npm install` still reaches the
//! internet.

use std::fmt::Write as _;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, PoisonError, RwLock};
use std::time::Duration;
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::net::{TcpListener, TcpStream};

use crate::routes::Prefix;
use crate::socks;
use crate::tsnet::SocksTarget;

/// Picks the tailnet for a host name or address.
pub trait Router: Send + Sync + 'static {
    /// The tailnet's SOCKS5 proxy, and the host to ask it for (a name of your
    /// own is replaced by its address).
    fn route(&self, host: &str) -> Option<(SocksTarget, String)>;
    /// A second copy of the app asked us to show our window.
    fn show(&self);
    /// The terminal proxy's address, for `tl`.
    fn terminal_proxy(&self) -> String {
        String::new()
    }
    /// Pings `host` once with Tailscale's own ping, for `tl ping`. Blocks.
    fn ping(&self, _host: &str) -> PingAnswer {
        PingAnswer::default()
    }
}

/// What a proxy does with a name no tailnet carries.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Fallback {
    /// Refuses it. The system proxy setting only sends tailnet names here, and
    /// the website pictures must not reach anything else.
    Refuse,
    /// Connects to it directly: the terminal proxy.
    Direct,
}

/// How long a direct connection may take to open.
const DIRECT_TIMEOUT: Duration = Duration::from_secs(20);

/// One answer to `tl ping`, sent as JSON.
#[derive(Clone, Debug, Default, PartialEq, serde::Serialize)]
pub struct PingAnswer {
    /// False: no tailnet carries the host, so `tl` runs the normal ping.
    pub routed: bool,
    /// The tailnet that carries it.
    pub tailnet: String,
    /// The machine that answered (a subnet router, for an address behind one).
    pub node: String,
    pub node_ip: String,
    /// How: an address and port when direct, "DERP(code)" through a relay.
    pub via: String,
    pub ms: f64,
    /// No answer in time.
    pub timeout: bool,
    /// Why it couldn't ping (translated).
    pub error: String,
}

/// The PAC rules and whether routing is on (off = PAC says "everything direct").
pub struct PacState {
    pac: RwLock<Vec<u8>>,
    active: AtomicBool,
}

pub const DIRECT_PAC: &str = "// Tailnet Link: routing is off, everything goes direct.\nfunction FindProxyForURL(url, host) { return \"DIRECT\"; }\n";

impl PacState {
    pub fn new() -> Self {
        PacState { pac: RwLock::new(DIRECT_PAC.as_bytes().to_vec()), active: AtomicBool::new(false) }
    }
    pub fn set_pac(&self, pac: Vec<u8>) {
        *self.pac.write().unwrap_or_else(PoisonError::into_inner) = pac;
    }
    pub fn set_active(&self, on: bool) {
        self.active.store(on, Ordering::SeqCst);
    }
    pub fn current(&self) -> Vec<u8> {
        if self.active.load(Ordering::SeqCst) {
            self.pac.read().unwrap_or_else(PoisonError::into_inner).clone()
        } else {
            DIRECT_PAC.as_bytes().to_vec()
        }
    }
}

/// What the PAC sends to the app.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct PacRules {
    /// Each of these and everything in it, e.g. example.ts.net.
    pub domains: Vec<String>,
    /// Exact names and addresses, e.g. a machine shared in from another tailnet,
    /// 100.101.102.103, or a name of your own.
    pub hosts: Vec<String>,
    /// Address ranges, e.g. 192.168.0.0/16. Only addresses typed as addresses
    /// match: a name is never looked up to see where it points.
    pub subnets: Vec<Prefix>,
}

/// PAC script sending what `rules` lists to `proxy_addr`, everything else direct.
pub fn build_pac(proxy_addr: &str, rules: &PacRules) -> Vec<u8> {
    // JSON string literals are valid JavaScript string literals.
    let js = |s: &str| serde_json::Value::from(s).to_string();
    let proxy = format!("return \"PROXY {proxy_addr}\";");
    let mut s = String::from("// Generated by Tailnet Link. Only these go through the other tailnets.\n");
    let hosts: Vec<String> =
        rules.hosts.iter().map(|h| crate::routes::normalize(h)).filter(|h| !h.is_empty()).collect();
    if !hosts.is_empty() {
        s.push_str("var tailnetLinkHosts = {\n");
        for h in &hosts {
            let _ = writeln!(s, "  {}: 1,", js(h));
        }
        s.push_str("};\n");
    }
    s.push_str("function FindProxyForURL(url, host) {\n  host = host.toLowerCase();\n");
    s.push_str("  if (host.charAt(0) === \"[\") host = host.substring(1, host.length - 1);\n");
    if !hosts.is_empty() {
        let _ = writeln!(s, "  if (tailnetLinkHosts.hasOwnProperty(host)) {proxy}");
    }
    for d in &rules.domains {
        let d = d.trim().trim_matches('.').to_lowercase();
        if d.is_empty() {
            continue;
        }
        let (q, dq) = (js(&d), js(&format!(".{d}")));
        let _ = writeln!(s, "  if (host === {q} || dnsDomainIs(host, {dq})) {proxy}");
    }
    let v4: Vec<&Prefix> = rules.subnets.iter().filter(|p| p.addr.is_ipv4()).collect();
    if !v4.is_empty() {
        s.push_str("  if (/^\\d+\\.\\d+\\.\\d+\\.\\d+$/.test(host)) {\n");
        for p in v4 {
            let (net, mask) = (js(&p.addr.to_string()), js(&p.v4_mask().unwrap_or_default()));
            let _ = writeln!(s, "    if (isInNet(host, {net}, {mask})) {proxy}");
        }
        s.push_str("  }\n");
    }
    let v6: Vec<&Prefix> = rules.subnets.iter().filter(|p| !p.addr.is_ipv4()).collect();
    if !v6.is_empty() {
        // isInNetEx is the IPv6-capable version (Chrome, Edge, Windows); without it, they go direct.
        s.push_str("  if (host.indexOf(\":\") >= 0 && typeof isInNetEx === \"function\") {\n");
        for p in v6 {
            let _ = writeln!(s, "    if (isInNetEx(host, {})) {proxy}", js(&p.to_string()));
        }
        s.push_str("  }\n");
    }
    s.push_str("  return \"DIRECT\";\n}\n");
    s.into_bytes()
}

/// Same PAC address apart from the ?v= version.
pub fn is_our_pac(a: &str, b: &str) -> bool {
    let base = |u: &str| u.split('?').next().unwrap_or("").to_owned();
    !a.is_empty() && base(a) == base(b)
}

/// A PAC address in the form this app (and its earlier versions) uses, on any
/// port: `http://127.0.0.1:PORT/proxy.pac`, with or without `?v=`. Left behind
/// by an earlier copy that ran on another port, it's safe to take over.
pub fn is_tailnet_link_pac(url: &str) -> bool {
    let Some(rest) = url.strip_prefix("http://127.0.0.1:") else { return false };
    let Some((port, path)) = rest.split_once('/') else { return false };
    let path = path.split('?').next().unwrap_or("");
    !port.is_empty() && port.len() <= 5 && port.bytes().all(|b| b.is_ascii_digit()) && path == "proxy.pac"
}

pub async fn serve(listener: TcpListener, router: Arc<dyn Router>, pac: Arc<PacState>, fallback: Fallback) {
    loop {
        let Ok((conn, _)) = listener.accept().await else {
            continue;
        };
        let (router, pac) = (router.clone(), pac.clone());
        tokio::spawn(async move {
            if let Err(e) = handle(conn, router, pac, fallback).await {
                log::debug!("proxy connection: {e}");
            }
        });
    }
}

/// Opens a connection to host:port through the tailnet that carries it, or
/// directly when none does and `fallback` allows it.
async fn open(router: &dyn Router, host: &str, port: u16, fallback: Fallback) -> Result<TcpStream, String> {
    if let Some((target, dial)) = router.route(host) {
        return socks::connect(&target, &dial, port).await.map_err(|e| {
            log::info!("connect {host}:{port}: {e}");
            format!("Tailnet Link: {e}")
        });
    }
    match fallback {
        Fallback::Refuse => Err(format!("no connected tailnet handles {host}")),
        Fallback::Direct => match tokio::time::timeout(DIRECT_TIMEOUT, TcpStream::connect((host, port))).await {
            Ok(Ok(s)) => Ok(s),
            Ok(Err(e)) => Err(format!("{host}:{port}: {e}")),
            Err(_) => Err(format!("{host}:{port} didn't answer within {}s", DIRECT_TIMEOUT.as_secs())),
        },
    }
}

const MAX_HEAD: usize = 64 * 1024;

async fn handle(
    mut client: TcpStream,
    router: Arc<dyn Router>,
    pac: Arc<PacState>,
    fallback: Fallback,
) -> std::io::Result<()> {
    // Read the request head.
    let mut buf = Vec::with_capacity(4096);
    let head_len = loop {
        let mut chunk = [0u8; 4096];
        let n = client.read(&mut chunk).await?;
        if n == 0 {
            return Ok(());
        }
        buf.extend_from_slice(&chunk[..n]);
        if let Some(i) = find(&buf, b"\r\n\r\n") {
            break i + 4;
        }
        if buf.len() > MAX_HEAD {
            return respond(&mut client, 431, "text/plain", b"request head too large").await;
        }
    };

    let mut headers = [httparse::EMPTY_HEADER; 96];
    let mut req = httparse::Request::new(&mut headers);
    if req.parse(&buf[..head_len]).is_err() {
        return respond(&mut client, 400, "text/plain", b"bad request").await;
    }
    let method = req.method.unwrap_or("").to_owned();
    let path = req.path.unwrap_or("").to_owned();
    let rest = buf[head_len..].to_vec();

    if method.eq_ignore_ascii_case("CONNECT") {
        let (host, port) = split_host_port(&path, 443);
        let mut up = match open(&*router, &host, port, fallback).await {
            Ok(s) => s,
            Err(e) => return respond(&mut client, 502, "text/plain", e.as_bytes()).await,
        };
        client.write_all(b"HTTP/1.1 200 Connection Established\r\n\r\n").await?;
        if !rest.is_empty() {
            up.write_all(&rest).await?;
        }
        let _ = tokio::io::copy_bidirectional(&mut client, &mut up).await;
        return Ok(());
    }

    if let Some(after) = path.strip_prefix("http://") {
        // Plain-HTTP proxy request: http://host[:port]/path
        let (authority, origin) = match after.find('/') {
            Some(i) => (&after[..i], &after[i..]),
            None => (after, "/"),
        };
        let (host, port) = split_host_port(authority, 80);
        let mut up = match open(&*router, &host, port, fallback).await {
            Ok(s) => s,
            Err(e) => return respond(&mut client, 502, "text/plain", e.as_bytes()).await,
        };
        // Rewrite to an origin-form request; one request per connection.
        let mut out = format!("{method} {origin} HTTP/1.1\r\n");
        for h in req.headers.iter() {
            let name = h.name.to_ascii_lowercase();
            if matches!(name.as_str(), "proxy-connection" | "proxy-authorization" | "connection" | "keep-alive") {
                continue;
            }
            out.push_str(h.name);
            out.push_str(": ");
            out.push_str(&String::from_utf8_lossy(h.value));
            out.push_str("\r\n");
        }
        out.push_str("Connection: close\r\n\r\n");
        up.write_all(out.as_bytes()).await?;
        if !rest.is_empty() {
            up.write_all(&rest).await?;
        }
        let _ = tokio::io::copy_bidirectional(&mut client, &mut up).await;
        return Ok(());
    }

    // Requests addressed to the proxy itself.
    let local_path = path.split('?').next().unwrap_or("");
    // `tl` asks with its own header, and by this computer's address: a web page
    // can't send the header to another site, nor (pointing a name of its own
    // at 127.0.0.1) the Host.
    let from_tl = req.headers.iter().any(|h| h.name.eq_ignore_ascii_case("x-tailnet-link") && h.value == b"tl")
        && req.headers.iter().any(|h| h.name.eq_ignore_ascii_case("host") && is_loopback_host(h.value));
    match (method.as_str(), local_path) {
        ("GET", "/tl/info") if from_tl => {
            let info = serde_json::json!({
                "version": env!("CARGO_PKG_VERSION"),
                "terminal_proxy": router.terminal_proxy(),
            });
            respond(&mut client, 200, "application/json", info.to_string().as_bytes()).await
        }
        ("GET", "/tl/ping") if from_tl => {
            let host = query_param(&path, "host").unwrap_or_default();
            let answer = tokio::task::spawn_blocking(move || router.ping(&host)).await.unwrap_or_default();
            let body = serde_json::to_vec(&answer).unwrap_or_default();
            respond(&mut client, 200, "application/json", &body).await
        }
        ("GET", "/proxy.pac" | "/wpad.dat") => {
            respond(&mut client, 200, "application/x-ns-proxy-autoconfig", &pac.current()).await
        }
        ("POST", "/show") => {
            // A custom header: browsers can't send it cross-site without
            // permission, so web pages can't trigger this.
            let ok = req.headers.iter().any(|h| h.name.eq_ignore_ascii_case("x-tailnet-link") && h.value == b"show");
            if ok {
                router.show();
                respond(&mut client, 204, "text/plain", b"").await
            } else {
                respond(&mut client, 403, "text/plain", b"forbidden").await
            }
        }
        _ => respond(&mut client, 200, "text/plain; charset=utf-8", b"Tailnet Link is running.\n").await,
    }
}

async fn respond(c: &mut TcpStream, code: u16, ctype: &str, body: &[u8]) -> std::io::Result<()> {
    let reason = match code {
        200 => "OK",
        204 => "No Content",
        400 => "Bad Request",
        403 => "Forbidden",
        431 => "Request Header Fields Too Large",
        _ => "Bad Gateway",
    };
    let head = format!(
        "HTTP/1.1 {code} {reason}\r\nContent-Type: {ctype}\r\nContent-Length: {}\r\nCache-Control: no-cache, no-store\r\nConnection: close\r\n\r\n",
        body.len()
    );
    c.write_all(head.as_bytes()).await?;
    c.write_all(body).await?;
    c.shutdown().await
}

/// A Host header naming this computer: 127.0.0.1, localhost or `[::1]`, with any port.
fn is_loopback_host(value: &[u8]) -> bool {
    let v = String::from_utf8_lossy(value).to_ascii_lowercase();
    let (host, _) = split_host_port(v.trim(), 0);
    matches!(host.as_str(), "127.0.0.1" | "localhost" | "::1")
}

/// A query parameter, %-decoded (`+` is a space).
fn query_param(path: &str, name: &str) -> Option<String> {
    let query = path.split_once('?')?.1;
    let value = query.split('&').find_map(|kv| kv.strip_prefix(name)?.strip_prefix('='))?;
    let bytes = value.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        let hex = bytes.get(i + 1..i + 3).and_then(|h| u8::from_str_radix(std::str::from_utf8(h).ok()?, 16).ok());
        match (bytes[i], hex) {
            (b'%', Some(b)) => {
                out.push(b);
                i += 3;
                continue;
            }
            (b'+', _) => out.push(b' '),
            (b, _) => out.push(b),
        }
        i += 1;
    }
    String::from_utf8(out).ok()
}

fn find(h: &[u8], needle: &[u8]) -> Option<usize> {
    h.windows(needle.len()).position(|w| w == needle)
}

/// "host:port" / "[v6]:port" / "host" -> (host, port)
pub fn split_host_port(s: &str, default_port: u16) -> (String, u16) {
    if let Some(rest) = s.strip_prefix('[')
        && let Some((h, p)) = rest.split_once(']')
    {
        let port = p.strip_prefix(':').and_then(|p| p.parse().ok()).unwrap_or(default_port);
        return (h.to_owned(), port);
    }
    match s.rsplit_once(':') {
        Some((h, p)) if !h.contains(':') => (h.to_owned(), p.parse().unwrap_or(default_port)),
        _ => (s.to_owned(), default_port),
    }
}

/// Serves one port forward until the task is aborted.
pub async fn serve_forward(listener: TcpListener, target: String, router: Arc<dyn Router>) {
    let (host, port) = split_host_port(&target, 0);
    loop {
        let Ok((mut conn, _)) = listener.accept().await else {
            continue;
        };
        let (router, host) = (router.clone(), host.clone());
        tokio::spawn(async move {
            let Some((t, dial)) = router.route(&host) else {
                log::info!("forward to {host}: no connected tailnet handles it");
                return;
            };
            match socks::connect(&t, &dial, port).await {
                Ok(mut up) => {
                    let _ = tokio::io::copy_bidirectional(&mut conn, &mut up).await;
                }
                Err(e) => log::info!("forward to {host}:{port}: {e}"),
            }
        });
    }
}

